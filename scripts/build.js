// Runs the full pipeline on data/telemetry.json and writes data/run.json for the page.
const fs = require('fs'), path = require('path');
const AH = require('../core.js');
const dir = path.join(__dirname, '..', 'data');
const tel = JSON.parse(fs.readFileSync(path.join(dir, 'telemetry.json')));
const truth = JSON.parse(fs.readFileSync(path.join(dir, 'truth.json')));
const sc = { seed: tel.seed, arr: AH.makeArray(tel.array), telemetry: tel.pairs, truth };
const t0 = Date.now();
const res = AH.run(sc);
const val = AH.validate(sc, res.dx);
const r = (x, d = 4) => (x === undefined || x === null || !isFinite(x) ? x : Math.round(x * 10 ** d) / 10 ** d);
const out = {
  generated: new Date().toISOString().slice(0, 10), seed: tel.seed, ms: Date.now() - t0, cfg: res.cfg,
  mainU: r(res.mainU), mainV: r(res.mainV), refine: res.refine,
  pairsUsed: res.dx.pairsUsed, pairsTotal: res.dx.pairsTotal,
  elems: res.dx.elems.map((e) => ({ s: e.status, td: e.txDead, rd: e.rxDead, g: r(e.txGainDb, 3), gse: r(e.txGainSeDb, 3), p: r(e.txPhaseDeg, 2), pse: r(e.txPhaseSeDeg, 2), rg: r(e.rxGainDb, 3), rp: r(e.rxPhaseDeg, 2), tm: r(e.txMedDb, 1), rm: r(e.rxMedDb, 1) })),
  syn: { wr: Array.from(res.syn.wr).map((x) => r(x, 6)), wi: Array.from(res.syn.wi).map((x) => r(x, 6)), iters: res.syn.history.length },
  taper: Array.from(res.taper).map((x) => r(x, 6)),
  results: Object.fromEntries(Object.entries(res.results).map(([k, v]) => [k, v.map((x) => ({ t: x.dir.theta, f: x.dir.phi, u: r(x.dir.u), v: r(x.dir.v), w: r(x.worstDb, 3), pk: r(x.peakDb, 3), ok: x.pass, at: x.at.map((y) => r(y)) }))])),
  summary: res.summary, validation: val,
};
fs.writeFileSync(path.join(dir, 'run.json'), JSON.stringify(out));
console.log(JSON.stringify({ ms: out.ms, refine: res.refine, summary: res.summary, validation: val }, null, 1));
// Browser bundle (works from file:// and GitHub Pages without fetch).
fs.writeFileSync(path.join(dir, 'bundle.js'), '/* generated by scripts/build.js */\nwindow.AH_DATA = ' + JSON.stringify({ telemetry: tel, truth, run: out }) + ';\n');
